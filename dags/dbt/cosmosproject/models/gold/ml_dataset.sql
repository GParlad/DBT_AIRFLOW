SELECT 
C.CUSTOMER_ID
,CASE WHEN C.GENDER = 'Male' THEN 1 ELSE 0 END AS GENDER
,C.AGE
,CASE WHEN C.MARRIED = 'Yes' THEN 1 ELSE 0 END AS MARRIED
,C.NUMBER_OF_DEPENDENTS
,C.ZIP_CODE
,C.NUMBER_OF_REFERRALS
,C.TENURE_IN_MONTHS
,CASE WHEN C.OFFER = 'Offer A' THEN 1 WHEN C.OFFER = 'Offer B' THEN 2 WHEN C.OFFER = 'Offer C' THEN 3 WHEN C.OFFER = 'Offer D' THEN 4 WHEN C.OFFER = 'Offer E' THEN 5 ELSE 0 END AS OFFER
,CASE WHEN C.PHONE_SERVICE = 'Yes' THEN 1 ELSE 0 END AS PHONE_SERVICE
,IFNULL(C.AVG_MONTHLY_LONG_DISTANCE_CHARGES, 0.00) AS AVG_MONTHLY_LONG_DISTANCE_CHARGES
,CASE WHEN C.MULTIPLE_LINES = 'Yes' THEN 1 WHEN C.MULTIPLE_LINES = NULL THEN 2 ELSE 0 END AS MULTIPLE_LINES
,CASE WHEN C.INTERNET_SERVICE = 'Yes' THEN 1 ELSE 0 END AS INTERNET_SERVICE
,CASE WHEN C.INTERNET_TYPE = 'Cable' THEN 1 WHEN C.INTERNET_TYPE = 'Fiber Optic' THEN 2 WHEN C.INTERNET_TYPE = NULL THEN 0 ELSE 3 END AS INTERNET_TYPE
,IFNULL(C.AVG_MONTHLY_GB_DOWNLOAD, 0.00) AS AVG_MONTHLY_GB_DOWNLOAD
,CASE WHEN C.ONLINE_SECURITY = 'Yes' THEN 1 WHEN C.ONLINE_SECURITY = NULL THEN 2 ELSE 0 END AS ONLINE_SECURITY
,CASE WHEN C.ONLINE_BACKUP = 'Yes' THEN 1 WHEN C.ONLINE_BACKUP = NULL THEN 2 ELSE 0 END AS ONLINE_BACKUP
,CASE WHEN C.DEVICE_PROTECTION_PLAN = 'Yes' THEN 1 WHEN C.DEVICE_PROTECTION_PLAN = NULL THEN 2 ELSE 0 END AS DEVICE_PROTECTION_PLAN
,CASE WHEN C.PREMIUM_TECH_SUPPORT = 'Yes' THEN 1 WHEN C.PREMIUM_TECH_SUPPORT = NULL THEN 2 ELSE 0 END AS PREMIUM_TECH_SUPPORT
,CASE WHEN C.STREAMING_TV = 'Yes' THEN 1 WHEN C.STREAMING_TV = NULL THEN 2 ELSE 0 END AS STREAMING_TV
,CASE WHEN C.STREAMING_MOVIES = 'Yes' THEN 1 WHEN C.STREAMING_MOVIES = NULL THEN 2 ELSE 0 END AS STREAMING_MOVIES
,CASE WHEN C.STREAMING_MUSIC = 'Yes' THEN 1 WHEN C.STREAMING_MUSIC = NULL THEN 2 ELSE 0 END AS STREAMING_MUSIC
,CASE WHEN C.UNLIMITED_DATA = 'Yes' THEN 1 WHEN C.UNLIMITED_DATA = NULL THEN 2 ELSE 0 END AS UNLIMITED_DATA
,CASE WHEN C.CONTRACT = 'One Year' THEN 1 WHEN C.CONTRACT = 'Two Year' THEN 2 ELSE 0 END AS CONTRACT
,CASE WHEN C.PAPERLESS_BILLING = 'Yes' THEN 1 ELSE 0 END AS PAPERLESS_BILLING
,CASE WHEN C.PAYMENT_METHOD = 'Bank Withdrawal' THEN 1 WHEN C.CONTRACT = 'Credit Card' THEN 2 ELSE 0 END AS PAYMENT_METHOD
,C.MONTHLY_CHARGE
,C.TOTAL_CHARGES
,C.TOTAL_EXTRA_DATA_CHARGES
,C.TOTAL_LONG_DISTANCE_CHARGES
,C.TOTAL_REVENUE
,CASE WHEN C.CUSTOMER_STATUS = 'Stayed' THEN 1 ELSE 0 END AS CUSTOMER_STATUS
FROM {{ref('telecom_customers_churns')}}  C
WHERE C.CUSTOMER_STATUS <> 'Joined'